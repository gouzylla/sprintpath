create table if not exists public.skills (
  id bigint generated by default as identity primary key,
  domain text not null check (domain in ('sql', 'python', 'english')),
  name text not null unique,
  level integer not null default 1,
  next_review_at timestamptz not null default now()
);

create table if not exists public.exercises (
  id bigint generated by default as identity primary key,
  skill_id bigint not null references public.skills(id) on delete cascade,
  domain text not null check (domain in ('sql', 'python', 'english')),
  prompt text not null,
  expected_answer text not null,
  explanation text not null,
  difficulty integer not null default 1 check (difficulty between 1 and 5),
  duration_seconds integer not null default 180
);

create table if not exists public.attempts (
  id bigint generated by default as identity primary key,
  exercise_id bigint not null references public.exercises(id) on delete cascade,
  answer text not null,
  score double precision not null,
  feedback text not null,
  duration_seconds integer not null,
  created_at timestamptz not null default now()
);

create index if not exists attempts_created_at_idx on public.attempts(created_at desc);
create index if not exists exercises_domain_difficulty_idx on public.exercises(domain, difficulty);

